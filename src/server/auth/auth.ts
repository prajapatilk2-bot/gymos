import { betterAuth } from "better-auth";
import { admin as adminPlugin } from "better-auth/plugins";
import { prismaAdapter } from "better-auth/adapters/prisma";

import { prisma } from "@/server/db/prisma";

// Better Auth (W3). Email + password for staff today; the additional-fields
// and plugin list below are deliberately structured so that phone OTP / 2FA
// can be added later (see docs/ARCHITECTURE.md "Auth & RBAC design") without
// reshaping the user model.
export const auth = betterAuth({
  basePath: "/api/v1/auth",
  secret: process.env.BETTER_AUTH_SECRET,
  baseURL: process.env.BETTER_AUTH_URL,
  database: prismaAdapter(prisma, { provider: "postgresql" }),
  // IDs are generated by Postgres (cuid default in schema.prisma), not by
  // Better Auth, so every table's primary key follows the same convention.
  advanced: {
    database: {
      generateId: false,
    },
  },
  emailAndPassword: {
    enabled: true,
    // Minimum-length gate only; full strength rules (upper/lower/digit/symbol)
    // are enforced server-side via src/server/auth/password.ts wherever a
    // password is accepted from a form (admin create-user, reset-password).
    minPasswordLength: 10,
    maxPasswordLength: 128,
  },
  session: {
    // Absolute session lifetime. Inactivity-based auto-logout (shorter, and
    // configurable per organization) is enforced separately in
    // src/server/auth/session.ts, since Better Auth's own config is static
    // at process start.
    expiresIn: 60 * 60 * 24 * 7, // 7 days
    updateAge: 60 * 10, // extend the session at most once every 10 minutes
  },
  user: {
    additionalFields: {
      organizationId: { type: "string", required: true, input: true },
      employeeCode: { type: "string", required: false, input: true },
      phone: { type: "string", required: false, input: true },
      isActive: {
        type: "boolean",
        required: false,
        input: false,
        defaultValue: true,
      },
      mustChangePassword: {
        type: "boolean",
        required: false,
        input: false,
        defaultValue: false,
      },
      lastLoginAt: { type: "date", required: false, input: false },
    },
  },
  plugins: [adminPlugin()],
});

export type Auth = typeof auth;
